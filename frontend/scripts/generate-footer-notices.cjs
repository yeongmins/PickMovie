const fs = require("fs");
const path = require("path");
const cp = require("child_process");

function escapeForDoubleQuote(value) {
  return String(value)
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r/g, "")
    .replace(/\n/g, " ");
}

function getRepoRoot(cwd) {
  try {
    return cp.execSync("git rev-parse --show-toplevel", {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
}

function normalizeSpacing(text) {
  return String(text).replace(/\s+/g, " ").trim();
}

function simplifyTechnicalTerms(text) {
  return normalizeSpacing(text)
    .replace(/\b[Pp]icky\b/g, "추천")
    .replace(/\b[Ss]earch\b/g, "검색")
    .replace(/\bUI\s*\/?\s*UX\b/gi, "화면 사용성")
    .replace(/\bCSS\b/g, "화면 스타일")
    .replace(/\bDB\b/g, "데이터베이스")
    .replace(/\bAPI\b/g, "데이터 연동")
    .replace(/메타데이터/g, "콘텐츠 정보")
    .replace(/라우팅/g, "페이지 이동")
    .replace(/리팩토링/g, "구조 개선")
    .replace(/코드 이관/g, "기능 이전")
    .replace(/최적화/g, "속도 개선");
}

function parseCommit(rawSubject) {
  const subject = normalizeSpacing(rawSubject);
  const match = subject.match(/^([a-zA-Z]+)(?:\([^)]+\))?:\s*(.+)$/);
  if (!match) {
    return { type: "update", topic: simplifyTechnicalTerms(subject) };
  }
  return {
    type: match[1].toLowerCase(),
    topic: simplifyTechnicalTerms(match[2]),
  };
}

function makeNoticeTitle(type, topic) {
  const typeTitleMap = {
    feat: "기능 업데이트",
    fix: "오류 수정",
    design: "디자인 개선",
    refactor: "구조 개선",
    chore: "서비스 안정화",
    docs: "문서 업데이트",
    merge: "코드 통합",
  };
  const base = typeTitleMap[type] || "서비스 업데이트";
  if (!topic) return base;
  return `${base}: ${topic}`;
}

function makeNoticeBody(type, topic) {
  if (!topic) return "서비스 전반의 품질과 사용성을 개선했습니다.";
  if (type === "fix") {
    return `${topic} 관련 문제를 수정해 안정성을 높였습니다.`;
  }
  if (type === "docs") {
    return `${topic} 내용을 최신 기준에 맞게 정리했습니다.`;
  }
  return `${topic} 관련 업데이트를 반영했습니다.`;
}

function readGitLogs(repoRoot) {
  if (!repoRoot) return [];
  try {
    const raw = cp.execSync(
      "git log --pretty=format:%h%x7C%ad%x7C%s --date=short",
      {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
      },
    ).trim();

    if (!raw) return [];

    return raw
      .split("\n")
      .filter(Boolean)
      .map((line) => {
        const [, date, ...rest] = line.split("|");
        const rawSubject = rest.join("|") || "업데이트";
        const parsed = parseCommit(rawSubject);
        return {
          date: date || "",
          title: makeNoticeTitle(parsed.type, parsed.topic),
          body: makeNoticeBody(parsed.type, parsed.topic),
        };
      });
  } catch {
    return [];
  }
}

function toTsSource(items) {
  const rows = items
    .map(
      (item) =>
        `  { date: "${escapeForDoubleQuote(item.date)}", title: "${escapeForDoubleQuote(item.title)}", body: "${escapeForDoubleQuote(item.body)}" },`,
    )
    .join("\n");

  return `// AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.\n// Generated by scripts/generate-footer-notices.cjs\n\nexport type FooterNoticeItem = {\n  date: string;\n  title: string;\n  body: string;\n};\n\nexport const NOTICE_ITEMS: FooterNoticeItem[] = [\n${rows}\n];\n`;
}

function main() {
  const frontendRoot = path.resolve(__dirname, "..");
  const outputPath = path.join(frontendRoot, "src", "data", "footerNotices.generated.ts");
  const repoRoot = getRepoRoot(frontendRoot);
  const items = readGitLogs(repoRoot);
  const source = toTsSource(items);

  fs.writeFileSync(outputPath, source, "utf8");
  process.stdout.write(`Generated ${items.length} notices -> ${outputPath}\n`);
}

main();
