function readDeveloperNotes(repoRoot) {
  if (!repoRoot) return [];
  try {
    const raw = cp.execSync(
      "git log --pretty=format:%h%x7C%ad%x7C%s --date=short",
      {
        cwd: repoRoot,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      },
    ).trim();

    if (!raw) return [];

    return raw
      .split("\n")
      .filter(Boolean)
      .map((line) => {
        const [hash, date, ...rest] = line.split("|");
        const rawSubject = rest.join("|") || "업데이트";
        const parsed = parseCommit(rawSubject);
        return {
          hash: hash || "",
          date: date || "",
          title: makeNoteTitle(parsed.type, parsed.topic),
          body: makeNoteBody(parsed.type, parsed.topic),
        };
      });
  } catch {
    return [];
  }
}

function toTsSource(notices, developerNotes) {
  const noticeRows = notices
    .map(
      (item) =>
        `  { date: "${escapeForDoubleQuote(item.date)}", title: "${escapeForDoubleQuote(item.title)}", body: "${escapeForDoubleQuote(item.body)}" },`,
    )
    .join("\n");

  const developerRows = developerNotes
    .map(
      (item) =>
        `  { hash: "${escapeForDoubleQuote(item.hash)}", date: "${escapeForDoubleQuote(item.date)}", title: "${escapeForDoubleQuote(item.title)}", body: "${escapeForDoubleQuote(item.body)}" },`,
    )
    .join("\n");

  return `// AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.\n// Generated by scripts/generate-footer-notices.cjs\n\nexport type FooterNoticeItem = {\n  date: string;\n  title: string;\n  body: string;\n};\n\nexport type FooterDeveloperNoteItem = {\n  hash: string;\n  date: string;\n  title: string;\n  body: string;\n};\n\nexport const NOTICE_ITEMS: FooterNoticeItem[] = [\n${noticeRows}\n];\n\nexport const DEVELOPER_NOTE_ITEMS: FooterDeveloperNoteItem[] = [\n${developerRows}\n];\n`;
}

function main() {
  const frontendRoot = path.resolve(__dirname, "..");
  const outputPath = path.join(frontendRoot, "src", "data", "footerNotices.generated.ts");
  const repoRoot = getRepoRoot(frontendRoot);
  const developerNotes = readDeveloperNotes(repoRoot);
  const notices = getDefaultNotices();
  const source = toTsSource(notices, developerNotes);

  fs.writeFileSync(outputPath, source, "utf8");
  process.stdout.write(
    `Generated ${notices.length} notices and ${developerNotes.length} developer notes -> ${outputPath}\n`,
  );
}

main();
